const MESSAGES: Record<Lang, Record<MessageKey, string>> = { UZ: uz, RU: ru, EN: en };

export function hasMessage(key: string): key is MessageKey {
  return key in MESSAGES[DEFAULT_LANG];
}

/** A variable whose value is itself a message key (e.g. `stage_PACKING`) is translated too. */
export function translate(lang: Lang, key: MessageKey, vars: MessageVars = {}): string {
  let text = MESSAGES[lang]?.[key] ?? MESSAGES[DEFAULT_LANG][key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    const value = typeof v === 'string' && hasMessage(v) ? translate(lang, v) : String(v);
    text = text.replaceAll(`{${k}}`, value);
  }
  return text;
}

/** Reads the caller language from `X-Lang`, falling back to `Accept-Language`. */
export function resolveLang(headers: Record<string, unknown>): Lang {
  const raw = String(headers['x-lang'] ?? headers['accept-language'] ?? '').slice(0, 2).toUpperCase();
  return raw === 'RU' || raw === 'EN' || raw === 'UZ' ? raw : DEFAULT_LANG;
}
